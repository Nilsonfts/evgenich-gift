def get_booking_confirmation_text(data: dict[str, str]) -> str:
    """Собрать текст подтверждения брони."""
    source_names = {
        'source_vk': 'ВКонтакте',
        'source_inst': 'Instagram', 
        'source_bot_tg': 'Бот в ТГ',
        'source_tg': 'Забронируй Евгенича'
    }
    from core.admin_config import get_bar_by_callback as _get_bar
    source_display = source_names.get(data.get('source', ''), data.get('source', 'не указано'))
    _bar_obj = _get_bar(data.get('bar', ''))
    bar_display = _bar_obj['name'] if _bar_obj else data.get('bar', 'не указано')
    
    # Если это гостевое бронирование (без источника), не показываем источник
    if data.get('is_guest_booking'):
        return (
            "📋 Правильно всё записал?\n\n"
            f"📌 Имя: {data.get('name', 'не указано')}\n"
            f"☎️ Телефон: {data.get('phone', 'не указано')}\n"
            f"📆 Дата: {data.get('date', 'не указано')}\n"
            f"🕒 Время: {data.get('time', 'не указано')}\n"
            f"👥 Гостей: {data.get('guests', 'не указано')}\n"
            f"🏠 Бар: {bar_display}"
        )
    else:
        # Админское бронирование с источником
        return (
            "📋 Правильно всё записал?\n\n"
            f"📌 Имя: {data.get('name', 'не указано')}\n"
            f"☎️ Телефон: {data.get('phone', 'не указано')}\n"
            f"📆 Дата: {data.get('date', 'не указано')}\n"
            f"🕒 Время: {data.get('time', 'не указано')}\n"
            f"👥 Гостей: {data.get('guests', 'не указано')}\n"
            f"📡 Источник: {source_display}\n"
            f"🏠 Бар: {bar_display}"
        )

def get_booking_report_text(data: dict[str, str], creator_id: int = None) -> str:
    """
    Формат внутреннего отчёта для бармена.
    
    Args:
        data: Данные бронирования
        creator_id: ID пользователя, создавшего бронь (None для бронирований от посетителей)
    """
    import time
    from utils.social_bookings_export import ALL_SOURCE_UTM_DATA, ALL_SOURCE_DISPLAY_NAMES, get_admin_name_by_id
    
    source = data.get('source', '')
    is_guest_booking = data.get('is_guest_booking', False)
    
    # Для гостевого бронирования без источника убираем UTM данные
    if is_guest_booking and not source:
        source_display = None
        utm_data = {}
    else:
        source_display = ALL_SOURCE_DISPLAY_NAMES.get(source, data.get('source', 'не указано'))
        utm_data = ALL_SOURCE_UTM_DATA.get(source, {})
    
    from core.admin_config import get_bar_by_callback as _get_bar_r
    _bar_obj_r = _get_bar_r(data.get('bar', ''))
    if _bar_obj_r:
        bar_display = _bar_obj_r['name']
        bar_tag = f"#{_bar_obj_r.get('code', '')}" if _bar_obj_r.get('code') else ''
    else:
        bar_display = data.get('bar', 'не указано')
        bar_tag = ''
    
    # Определяем создателя
    creator_name = "👤 Посетитель (через бота)"
    if creator_id:
        creator_name = get_admin_name_by_id(creator_id)
    
    # Получаем текущую дату и время для заявки
    from datetime import datetime
    current_datetime = datetime.now().strftime("%d.%m.%Y %H:%M")
    
    # Formed AMO tag (no '#' to keep it copy-paste friendly for AmoCRM)
    amo_tag_value = (data.get('amo_tag') or (_bar_obj_r.get('code', '') if _bar_obj_r else '') or '').strip()

    # Formируем красивое сообщение с HTML форматированием
    return (
        f"🚨 <b>НОВАЯ БРОНЬ!</b>\n\n"
        f"{bar_tag}\n"
        f"#бронь_соц_сети\n"
        + (f"🏷 AMO_TAG: <code>{amo_tag_value}</code>\n" if amo_tag_value else "") +
        f"⏰ <b>Создано:</b> {current_datetime}\n\n"
        
        f"📋 <b>Детали бронирования:</b>\n"
        f"👤 <b>Имя:</b> {data.get('name', 'не указано')}\n"
        f"📞 <b>Телефон:</b> {data.get('phone', 'не указано')}\n"
        f"📅 <b>Дата:</b> {data.get('date', 'не указано')}\n"
        f"⏰ <b>Время:</b> {data.get('time', 'не указано')}\n"
        f"👥 <b>Гости:</b> {data.get('guests', 'не указано')}\n"
        f"🏠 <b>Бар:</b> {bar_display}\n"
        + (f"📊 <b>Источник:</b> {source_display}\n" if source_display else "") +
        f"\n"
        
        + (f"📊 <b>UTM-метки:</b>\n"
        f"- Source: {utm_data.get('utm_source', '-')}\n"
        f"- Medium: {utm_data.get('utm_medium', '-')}\n"
        f"- Campaign: {utm_data.get('utm_campaign', '-')}\n"
        f"- Content: {utm_data.get('utm_content', '-')}\n"
        f"- Term: {utm_data.get('utm_term', '-')}\n\n" if utm_data else "") +
        
        f"🆔 <b>ID:</b> BID-{int(time.time())}\n"
        f"👤 <b>Создал:</b> {creator_name}"
    )

