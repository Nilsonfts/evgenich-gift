def get_welcome_text(user_id: int = 0) -> tuple:
    """Возвращает (текст, variant_id) для приветствия.

    Привязка к user_id даёт «липкий» вариант: один и тот же гость всегда
    видит одно и то же приветствие. Это корректно для A/B-теста.
    """
    if not WELCOME_VARIANTS:
        return WELCOME_TEXT, "control"
    idx = (int(user_id) if user_id else 0) % len(WELCOME_VARIANTS)
    variant_id, template = WELCOME_VARIANTS[idx]

    # Подставляем плейсхолдеры (только для вариантов, где они есть)
    fmt_kwargs = {}
    if "{redeemed_total}" in template:
        try:
            from core import database
            n = database.get_total_redeemed_count()
            # Округляем до сотен для красоты («2 800+» вместо «2 847»)
            rounded = max(100, (n // 100) * 100)
            fmt_kwargs["redeemed_total"] = f"{rounded:,}".replace(",", " ")
        except Exception:
            fmt_kwargs["redeemed_total"] = "2 000"
    try:
        text = template.format(**fmt_kwargs) if fmt_kwargs else template
    except Exception:
        text = template
    return text, variant_id


